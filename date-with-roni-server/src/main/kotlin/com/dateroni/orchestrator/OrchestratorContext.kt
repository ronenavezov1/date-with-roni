package com.dateroni.orchestrator

import com.dateroni.orchestrator.llm.LlmClient
import com.dateroni.objects.HerProfile
import com.dateroni.objects.Image
import com.dateroni.objects.Turn

// ============================================================
//  כל מה שהמנצח — והכלים והפעולות שלו — צריכים, מצומצם לשיחה
//  אחת.
//
//  מוגדר כאן, בחבילת המנצח, כי הוא הבעלים של החוזה שלו.
//  AgentRepository מספק את המימוש.
//
//  עקרון ההרשאה המזערית:
//    • אין גישה לשיחות אחרות. turns() תמיד מחזיר את זו הנוכחית.
//    • אין גישה לרפוזיטורי, ל-DB או לבניית LlmClient.
//    • הכלים והפעולות מקבלים בדיוק את אותו הקשר — ולכן אין להם
//      דרך *תחבירית* להשפיע על מישהי אחרת.
//
//  זה מה שהופך זליגה בין שיחות מבאג שצריך לתפוס לדבר שהקומפיילר
//  לא מאפשר.
// ============================================================

interface OrchestratorContext {

    // ── זהות ────────────────────────────────────────────────

    /** הכתובת של מי שמדברת עכשיו. הגבול של כל מה שמותר כאן. */
    val herEmail: String

    /** השם שלה, אם ידוע. */
    val herName: String?

    // ── תשתית ───────────────────────────────────────────────

    val llmClient: LlmClient

    // ── השיחה (מצומצם ל-herEmail) ───────────────────────────

    /** ההיסטוריה, לקריאה. */
    fun turns(): List<Turn>

    /** מוסיף תור להיסטוריה שבזיכרון. */
    fun appendTurn(turn: Turn)

    /**
     * האם היא כבר דיברה איתנו בעבר.
     *
     * נמדד לפי תקציב הטוקנים שנשרף: אפס = פעם ראשונה. זה עובד
     * דווקא כי התקציב **לא** מתאפס בין שיחות — הוא הזיכרון היחיד
     * שנשאר אחרי שההתכתבות נמחקה.
     *
     * שאלה אחת, בוליאנית. אין כאן גישה ל-DB ואין דרך לשאול על
     * מישהי אחרת.
     */
    suspend fun hasTalkedBefore(): Boolean

    /**
     * מסמן ב-DB שהוואטסאפ נמסר לה.
     *
     * הפעולה היחידה כאן שמשנה משהו מתמיד — ולכן היא נגישה רק
     * דרך Action, ורק לשיחה הנוכחית.
     */
    suspend fun markWhatsappGiven()

    // ── דייט ────────────────────────────────────────────────

    /** קובע דייט. מחליף את הקיים אם יש. */
    suspend fun scheduleDate(whenText: String, place: String, at: java.time.Instant? = null)

    /** מבטל את הדייט ומנקה את הפרטים. */
    suspend fun cancelDate()

    /** מה נקבע, אם נקבע. */
    suspend fun currentDate(): com.dateroni.objects.DateDetails?

    /** אילו תמונות כבר נשלחו בשיחה הזו. */
    fun sentPhotos(): Set<Int>

    /** מסמן שתמונה נשלחה, כדי שלא תישלח שוב. */
    fun markPhotoSent(index: Int)

    /** תקציר מה שכבר נמחק מההיסטוריה, אם תומצת. */
    fun summary(): String?

    /** כמה תמונות כבר צורפו לתשובה שנבנית עכשיו. */
    fun photosThisRound(): Int

    /** כמה תורות עברו מאז התמונה האחרונה. גדול מאוד = עוד לא נשלחה. */
    fun turnsSinceLastPhoto(): Int

    // ── פרופיל ──────────────────────────────────────────────

    /** הפרופיל המובנה של הבחורה. חולץ הפרופיל ממלא, המנתח קורא. */
    fun profile(): HerProfile

    // ── מה שיוצא החוצה ──────────────────────────────────────

    /**
     * שולח לה הודעה **עכשיו**, בלי לחכות לסוף הטיפול.
     *
     * ההודעה נכנסת לתיבת היוצא ומגיעה אליה בפינג הבא — בתוך
     * שנייה. זה מה שמאפשר לסוכן לומר "רגע, בודק…" ואז לחזור עם
     * התשובה האמיתית, במקום שקט ארוך.
     *
     * לא SharedFlow: זרם עם replay=0 היה מאבד הודעה שנשלחה בין
     * שני פינגים. לתיבה יש seq רץ, והלקוח מבקש מהנקודה שבה עצר.
     */
    fun sendMessage(text: String, images: List<Image> = emptyList())

    /**
     * מצרף תמונה לתשובה הנוכחית.
     *
     * המודל בוחר אינדקס; הקובץ נטען כאן. ה-base64 לעולם לא עובר
     * דרכו — הוא לא רואה אותו ולא מייצר אותו.
     */
    fun attachImage(image: Image)
}
