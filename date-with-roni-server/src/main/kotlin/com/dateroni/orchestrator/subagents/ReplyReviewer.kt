package com.dateroni.orchestrator.subagents

import com.dateroni.orchestrator.OrchestratorContext

// ============================================================
//  בודק את הטקסט לפני שהוא נשלח.
//
//  שער איכות אחרון: ארוך מדי, מתחנף, נשמע כמו בוט, המציא
//  עובדה, או שאל שתי שאלות בבת אחת.
//
//  מחזיר APPROVED או הצעת שיפור. הוא לא כותב מחדש בעצמו —
//  ההחלטה נשארת אצל המתכנן, שמכיר את השיחה טוב יותר.
// ============================================================

private const val PROMPT = """
תפקידך: לבדוק תשובה לפני שהיא נשלחת לאישה בשיחת היכרות.

פסול אם:
- ארוכה מדי (מעל שלוש-ארבע שורות בלי סיבה טובה)
- מתחנפת או מוכרת אותו ("הוא ממש מדהים!")
- נשמעת כמו עוזר קולי ("בשמחה! אשמח לעזור לך")
- שואלת שתי שאלות באותה הודעה
- טוענת עובדה על רוני שלא הופיעה בשיחה
- אימוג׳ים מיותרים, יותר מאחד

ענה:
APPROVED — אם היא בסדר
או משפט אחד שאומר מה לתקן. בלי לכתוב מחדש בעצמך.

היה מחמיר על אורך והתחנפות, סלחני על סגנון. תשובה טובה
שנשמעת קצת אישית עדיפה על תשובה מלוטשת.
"""

class ReplyReviewer(private val ctx: OrchestratorContext) {
    suspend fun review(draft: String): String = ctx.ask(
        id = "reply-reviewer",
        prompt = PROMPT,
        input = draft,
        fallback = "APPROVED",
    )
}
