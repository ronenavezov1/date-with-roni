package com.dateroni.orchestrator.roni

import kotlinx.serialization.Serializable

// ============================================================
//  הצורה של העובדות על רוני — בלי התוכן.
//
//  התוכן עצמו יושב ב-roni-facts.json (ראה RoniFacts.kt), מחוץ
//  לגיט. כאן רק השדות ומה כל אחד אומר.
//
//  כל שדה שנשאר ריק פשוט לא מגיע למודל, והכלי המתאים יחזיר
//  "רוני לא סיפר לי על זה". זה מכוון: עדיף שהוא יגיד שאינו
//  יודע מאשר שימציא משהו שנשמע סביר.
// ============================================================

@Serializable
data class RoniFactsData(

    // ────────────────────────────────────────────────────────
    //  פרטים יבשים
    // ────────────────────────────────────────────────────────

    /** למשל 29 */
    val age: Int,
    /** למשל "תל אביב" */
    val city: String,
    /** משפט אחד. למשל "מפתח תוכנה" */
    val work: String,
    val education: String,
    val drink: String,
    val smoke: String,
    val weed: String,
    /** מוצא */
    val origin: String,
    /** דת ויחס למסורת */
    val religion: String,
    /** איך אתה מגדיר את עצמך */
    val selfImage: String,
    /**
     * דעה פוליטית.
     *
     * חשוף בכלי נפרד ולא בפרטים היבשים, ורק כשהיא שואלת ישירות.
     * זו לא צנזורה — זה מה שאדם היה עושה. פוליטיקה שנזרקת בלי
     * שנשאלה מסיימת שיחות, וגם כשהיא נשאלת, התשובה צריכה להיות
     * מה שאתה באמת חושב ולא ניסוח מרוכך.
     */
    val politics: String,
    val tattos: String,
    /** גובה, מצב משפחתי, ילדים — מה שנוח לך שיֵדע */
    val extras: Map<String, String>,
    /** למשל ["בישול", "ריצה", "קולנוע"] */
    val interests: List<String>,
    /**
     * משחקי מחשב שאתה משחק.
     *
     * שדה משלו ולא שורה ב-interests: "לשחק במחשב" הוא תחביב,
     * אבל *אילו* משחקים זה פרט שאפשר לדבר עליו — והיא יכולה
     * להכיר אותם.
     */
    val games: List<String>,
    /** האופנוע, ומה שסביבו. */
    val motorcycle: String,
    /** מה אתה מחפש */
    val lookingFor: String,
    /** איך נראה דייט ראשון טוב מבחינתך */
    val idealFirstDate: String,
    val languages: List<String>,
    /** פסקה קצרה עליך, בגוף שלישי */
    val about: String,

    // ────────────────────────────────────────────────────────
    //  להעמקה: שירות צבאי, עבודה, ואיך נבנה האתר
    //
    //  כתוב בחופשיות; זה נמסר למודל כמו שהוא.
    // ────────────────────────────────────────────────────────

    /** איפה שירתת, מה עשית, מה לקחת מזה. */
    val militaryService: String,
    /** במה אתה עוסק באמת, מה מעניין אותך בזה, על מה עבדת. */
    val workDeepDive: String,
    /**
     * הסיפור מאחורי הפרויקט. זה גם דרך טובה להראות משהו עליך
     * בלי לספר עליך ישירות.
     */
    val howIBuiltThis: String,

    // ────────────────────────────────────────────────────────
    //  קצת ג׳וס — מה שהופך אותו למעניין
    //
    //  חומר לשיחה מעבר לפרטים היבשים. כל שדה חשוף בכלי משלו.
    // ────────────────────────────────────────────────────────

    /** מערכות יחסים ואקסיות — היסטוריה רומנטית, מה לקח מזה. */
    val relationships: String,
    /** חיי הדייטים — איך נראים לו דייטים, סיפורים, מה עובד עליו. */
    val datingLife: String,
    /** חיי השגרה — איך נראה יום או שבוע טיפוסי שלו. */
    val routine: String,

    // ────────────────────────────────────────────────────────
    //  עוד עליו — מהריאיון
    //
    //  עובדות רגילות לשיחה. לא ג׳וס: הכלים חושפים אותן חופשי,
    //  חוץ מ-turnOffs שנחשף רק אם היא שואלת.
    // ────────────────────────────────────────────────────────

    /** משפחה — הורים, אחים. */
    val family: String,
    /** אוכל. */
    val food: String,
    /** הבית — הדירה והוייב שלה. */
    val home: String,
    /** מוזיקה. */
    val music: String,
    /** שאיפות ותפיסת חיים. */
    val outlook: String,
    /** איך הוא רואה זוגיות. */
    val partnershipView: String,
    /** מה מוריד לו — נחשף רק אם היא שואלת. */
    val turnOffs: String,
    /** ספורט קרב והלוחמים האהובים. */
    val combatSports: String,
    /** קזינו. */
    val casino: String,
    /** נסיעות. */
    val travel: String,
    /** קוקטיילים. */
    val cocktails: String,
    /** חיות מחמד. */
    val pets: String,
    /** הקעקוע, והמשמעות. */
    val tattoo: String,
    /** דגל ירוק — מה כובש אותו. */
    val greenFlags: String,
    /** ילדים ועתיד. */
    val kids: String,
    /** במה הוא הכי גאה. */
    val proud: String,

    // ────────────────────────────────────────────────────────
    //  ההומור שלך
    //
    //  תת-סוכן מציע תגובות מצחיקות בסגנון שלך. בלי הדוגמאות
    //  האלה הוא יגיד במפורש שאין לו על מה להתבסס — במקום להמציא
    //  סגנון ולטעון שהוא שלך.
    // ────────────────────────────────────────────────────────

    /** איך ההומור שלך עובד. למשל "יבש, ציני, הרבה על חשבון עצמי" */
    val humorStyle: String,
    /** ★ דברים שבאמת אמרת. ככל שיותר, החיקוי מדויק יותר. ★ */
    val humorExamples: List<String>,

    // ────────────────────────────────────────────────────────
    //  הקול של ג׳ימיקלוד עצמו
    //
    //  לא הומור של רוני — הומור *של הסוכן*, על עצמו. השורות
    //  האלה נאמרות כשהוא נתקל בקיר: רוני לא מילא משהו, הוא
    //  לא יודע, או שהוא סתם מתפאר.
    //
    //  זה שדה נפרד מ-humorExamples בכוונה. שם זה חומר גלם
    //  לחיקוי הסגנון של רוני, וכל שורה בקול של רובוט שנכנסת
    //  לשם מלמדת את מחקה-ההומור שרוני מדבר על הראם שלו.
    // ────────────────────────────────────────────────────────

    /** דברים שהסוכן אומר על עצמו כשאין לו תשובה. */
    val agentSelfJokes: List<String>,

    /**
     * הטקסטים שאפשר להכניס מראש להודעת הוואטסאפ.
     *
     * כשהיא לוחצת על הקישור, ההודעה כבר כתובה לה בשדה — היא רק
     * צריכה לשלוח. תת-סוכן בוחר את המתאים לפי איך שהשיחה הלכה.
     */
    val whatsappTexts: List<String>,

    // ────────────────────────────────────────────────────────
    //  תמונות
    //
    //  הקבצים יושבים בתיקייה שמוגדרת ב-PHOTOS_DIR (ברירת מחדל:
    //  photos/ לצד הפרויקט). הכיתוב הוא מה שהמודל *רואה*, ולפיו
    //  הוא בוחר איזו תמונה מתאימה — אז שווה שיהיה תיאורי. בדיחת
    //  פוטושופ צריכה לומר בכיתוב שהיא בדיחה, אחרת המודל יספר
    //  אותה כעובדה.
    // ────────────────────────────────────────────────────────

    val photos: List<PhotoEntry>,
)

@Serializable
data class PhotoEntry(
    /** שם הקובץ בתוך תיקיית התמונות */
    val file: String,
    /** מה רואים בתמונה. זה מה שהמודל קורא. */
    val caption: String,
)
